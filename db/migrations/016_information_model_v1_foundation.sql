CREATE OR REPLACE FUNCTION public.validate_model_scope()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE a_brand integer; a_category integer; b_brand integer; b_category integer; variant_model integer;
BEGIN
    IF TG_TABLE_NAME='legacy_model_mapping' THEN
        SELECT brand_id,category_id INTO a_brand,a_category FROM public.models WHERE id=NEW.legacy_model_id;
        SELECT brand_id,category_id INTO b_brand,b_category FROM public.models WHERE id=NEW.canonical_model_id;
    ELSE
        SELECT brand_id,category_id INTO a_brand,a_category FROM public.models WHERE id=NEW.legacy_model_id;
        SELECT brand_id,category_id INTO b_brand,b_category FROM public.models WHERE id=NEW.candidate_model_id;
    END IF;
    IF (a_brand,a_category) IS DISTINCT FROM (b_brand,b_category) THEN RAISE EXCEPTION 'cross-scope model mapping is prohibited'; END IF;
    IF TG_TABLE_NAME='legacy_model_mapping' THEN
        IF NEW.model_variant_id IS NOT NULL THEN
            SELECT model_id INTO variant_model FROM public.model_variants WHERE id=NEW.model_variant_id;
            IF variant_model IS DISTINCT FROM NEW.canonical_model_id THEN RAISE EXCEPTION 'mapped variant must belong to canonical model'; END IF;
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER legacy_model_mapping_scope AFTER INSERT OR UPDATE ON public.legacy_model_mapping DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.validate_model_scope();
CREATE CONSTRAINT TRIGGER legacy_model_candidates_scope AFTER INSERT OR UPDATE ON public.legacy_model_mapping_candidates DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.validate_model_scope();

CREATE OR REPLACE FUNCTION public.validate_product_code_variant()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE variant_model integer;
BEGIN
    IF NEW.model_variant_id IS NULL THEN RETURN NEW; END IF;
    SELECT model_id INTO variant_model FROM public.model_variants WHERE id=NEW.model_variant_id;
    IF variant_model IS DISTINCT FROM NEW.model_id THEN RAISE EXCEPTION 'product code variant must belong to product code model'; END IF;
    RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER product_codes_variant_model AFTER INSERT OR UPDATE OF model_id,model_variant_id ON public.product_codes DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.validate_product_code_variant();

