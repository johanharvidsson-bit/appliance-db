CREATE OR REPLACE FUNCTION public.revalidate_affected_guide()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE affected_guide_id bigint; guide_row public.guides%ROWTYPE;
BEGIN
    affected_guide_id := CASE WHEN TG_OP='DELETE' THEN OLD.guide_id ELSE NEW.guide_id END;
    SELECT * INTO guide_row FROM public.guides WHERE id=affected_guide_id;
    IF FOUND AND guide_row.content_status='published' AND NOT guide_row.is_general AND
       NOT EXISTS(SELECT 1 FROM public.guide_error_codes WHERE guide_id=affected_guide_id AND relation_status='verified') AND
       NOT EXISTS(SELECT 1 FROM public.guide_faults WHERE guide_id=affected_guide_id AND relation_status='verified')
    THEN RAISE EXCEPTION 'published guide requires a verified topic or is_general=true'; END IF;
    RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
