     WHERE a.id=NEW.article_id;
    IF g_category IS DISTINCT FROM a_category OR (g_brand IS NOT NULL AND g_brand IS DISTINCT FROM a_brand) THEN
        RAISE EXCEPTION 'article guide relation crosses guide scope';
    END IF;
    RETURN NEW;
END $$;
