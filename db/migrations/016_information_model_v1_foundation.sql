CREATE OR REPLACE FUNCTION public.validate_url_redirect_activation()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE src public.url_registry%ROWTYPE; dst public.url_registry%ROWTYPE;
BEGIN
    IF NEW.approval_status NOT IN ('activated','verified') THEN RETURN NEW; END IF;
    SELECT * INTO src FROM public.url_registry WHERE id=NEW.source_url_id;
    SELECT * INTO dst FROM public.url_registry WHERE id=NEW.destination_url_id;
    IF (src.site_id,src.environment) IS DISTINCT FROM (dst.site_id,dst.environment) THEN RAISE EXCEPTION 'redirect crosses site or environment'; END IF;
    IF dst.http_status<>200 OR dst.canonical_url IS DISTINCT FROM dst.normalized_url THEN RAISE EXCEPTION 'redirect destination must be 200 and self-canonical'; END IF;
    IF EXISTS(SELECT 1 FROM public.url_redirects WHERE source_url_id=NEW.destination_url_id AND id<>NEW.id AND approval_status IN ('activated','verified')) THEN RAISE EXCEPTION 'redirect chain is prohibited'; END IF;
    IF NOT EXISTS(SELECT 1 FROM public.entity_url_bindings s JOIN public.entity_url_bindings d ON d.entity_key=s.entity_key WHERE s.url_id=NEW.source_url_id AND d.url_id=NEW.destination_url_id AND s.mapping_status='verified' AND d.mapping_status='verified' AND s.valid_to IS NULL AND d.valid_to IS NULL) THEN RAISE EXCEPTION 'redirect requires exact verified semantic binding'; END IF;
    RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER url_redirect_activation AFTER INSERT OR UPDATE ON public.url_redirects DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.validate_url_redirect_activation();

