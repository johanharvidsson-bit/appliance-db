CREATE OR REPLACE FUNCTION public.validate_article_guide_scope()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE g_brand integer; g_category integer; a_brand integer; a_category integer;
BEGIN
    SELECT brand_id,category_id INTO g_brand,g_category FROM public.guides WHERE id=NEW.guide_id;
    SELECT COALESCE(ec.brand_id,f.brand_id),COALESCE(ec.category_id,f.category_id)
      INTO a_brand,a_category
      FROM public.articles a
      LEFT JOIN public.error_codes ec ON ec.id=a.error_code_id
